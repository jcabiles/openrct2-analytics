"""Behavioral tests for scripts/generate_dbt_sources.py, on fixture contracts in a temp folder."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from dbt.clients.checked_load import checked_load

from generate_dbt_sources import generate, main
from openrct2_analytics.ingest.contracts import CONTRACTS_DIR, load_fields

# The data-root expression of the first lines of models/staging/_sources.yml, with its
# fail-closed default: dev and ci fall back to the sample, every other target to a missing folder.
DATA_ROOT = (
    "{{ var('parquet_root', 'data/sample/rehearsal' if target.name in ['dev', 'ci']"
    " else 'invalid-parquet-root') }}"
)
# The registry-root expression with its fail-closed default, written once as the registry source's
# config; each table's location names it through dbt-duckdb's {registry_root} placeholder.
REGISTRY_ROOT = (
    "{{ var('registry_root', 'data/sample/rehearsal/registry' if target.name in"
    " ['dev', 'ci'] else 'invalid-registry-root') }}"
)
REGISTRY_LOCATION = (
    "read_csv('{registry_root}/{file_glob}',"
    " header=true, filename=true, all_varchar=true, union_by_name=true)"
)
REGISTRY_FIELDS = [
    ("park_id", "string", "VARCHAR", True, "Park identifier; no unit."),
    ("delivered_on", "date", "DATE", True, "Delivery date; a date, no time."),
]
LABEL_FIELDS = [
    ("session_id", "string", "VARCHAR", True, "Session identifier; no unit."),
    ("play_mode", "string", "VARCHAR", True, "Managed or autopilot; text."),
    ("ready_confirmation", "string", "VARCHAR", False, "Empty or the ready phrase; text."),
]
REPO = Path(__file__).resolve().parent.parent

ENVELOPE_FIELDS = [
    ("park_id", "string", "VARCHAR", True, "Park identifier; text, no unit."),
    ("seq", "integer", "INTEGER", True, "Order within the session; a count from 1."),
    ("note", "string", "VARCHAR", False, "Free note the plugin may omit; text."),
]
TYPE_FIELDS = {
    "alpha": [("cash_tenths", "integer", "BIGINT", True, "Cash in tenths of a dollar.")],
    "beta": [("rating", "integer", "INTEGER", False, "Park rating, 0 to 1000.")],
}


def contract_text(name: str, fields: list[tuple[str, str, str, bool, str]]) -> str:
    lines = [
        "apiVersion: v3.2.0",
        "kind: DataContract",
        f"id: {name}",
        f"name: {name}",
        "version: 9.9.9",
        "status: active",
        "schema:",
        f"  - name: {name}",
        "    physicalType: view",
        "    properties:",
    ]
    for field, logical, physical, required, description in fields:
        lines += [
            f"      - name: {field}",
            f"        logicalType: {logical}",
            f"        physicalType: {physical}",
            f"        required: {str(required).lower()}",
            f"        description: {description}",
        ]
    return "\n".join(lines) + "\n"


def write_contracts(folder: Path) -> Path:
    folder.mkdir()
    reference = folder / "reference"
    reference.mkdir()
    (reference / "park_registry.odcs.yaml").write_text(
        contract_text("park_registry", REGISTRY_FIELDS)
    )
    (reference / "session_play_mode.odcs.yaml").write_text(
        contract_text("session_play_mode", LABEL_FIELDS)
    )
    (folder / "envelope.odcs.yaml").write_text(contract_text("envelope", ENVELOPE_FIELDS))
    for name, fields in TYPE_FIELDS.items():
        (folder / f"{name}.odcs.yaml").write_text(contract_text(name, fields))
    return folder


@pytest.fixture
def contracts(tmp_path: Path) -> Path:
    return write_contracts(tmp_path / "contracts")


def parsed(text: str, source_name: str = "landing") -> dict[str, dict[str, Any]]:
    """Return one source's generated tables by name, each with its columns by name."""
    data, failures = checked_load(text)
    assert not failures
    assert data is not None
    (source,) = (s for s in data["sources"] if s["name"] == source_name)
    return {
        table["name"]: {
            "config": table["config"],
            "columns": {column["name"]: column for column in table["columns"]},
        }
        for table in source["tables"]
    }


def test_two_generations_are_byte_identical(contracts: Path, tmp_path: Path) -> None:
    first, second = tmp_path / "first.yml", tmp_path / "second.yml"

    assert main(["--contracts-dir", str(contracts), "--output", str(first)]) == 0
    assert main(["--contracts-dir", str(contracts), "--output", str(second)]) == 0

    assert first.read_bytes() == second.read_bytes()
    assert first.read_text(encoding="utf-8") == generate(contracts)
    assert first.read_text(encoding="utf-8").startswith(
        "# Generated by `uv run python scripts/generate_dbt_sources.py`"
    )


def test_check_passes_on_a_fresh_file(contracts: Path, tmp_path: Path) -> None:
    output = tmp_path / "sources.yml"
    main(["--contracts-dir", str(contracts), "--output", str(output)])

    assert main(["--check", "--contracts-dir", str(contracts), "--output", str(output)]) == 0


def test_check_fails_naming_the_line_when_a_description_changes(
    contracts: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    output = tmp_path / "sources.yml"
    main(["--contracts-dir", str(contracts), "--output", str(output)])
    path = contracts / "alpha.odcs.yaml"
    path.write_text(path.read_text().replace("Cash in tenths", "Cash, in tenths"))
    capsys.readouterr()

    code = main(["--check", "--contracts-dir", str(contracts), "--output", str(output)])

    lines = generate(contracts).splitlines()
    changed = next(n for n, line in enumerate(lines, 1) if "Cash, in tenths" in line)
    assert code == 1
    err = capsys.readouterr().err
    assert f"line {changed}:" in err
    assert "Cash, in tenths" in err


def test_check_fails_when_the_file_is_missing(contracts: Path, tmp_path: Path) -> None:
    missing = tmp_path / "missing.yml"

    assert main(["--check", "--contracts-dir", str(contracts), "--output", str(missing)]) == 1


def test_every_table_carries_the_fail_closed_data_root(contracts: Path) -> None:
    tables = parsed(generate(contracts))

    assert sorted(tables) == ["alpha", "beta"]
    for name, table in tables.items():
        assert table["config"]["external_location"] == f"{DATA_ROOT}/v1/{name}.parquet"


def test_every_column_carries_its_contract_description(contracts: Path) -> None:
    tables = parsed(generate(contracts))

    expected = {
        "alpha": {f[0]: f[4] for f in ENVELOPE_FIELDS + TYPE_FIELDS["alpha"]},
        "beta": {f[0]: f[4] for f in ENVELOPE_FIELDS + TYPE_FIELDS["beta"]},
    }
    for name, table in tables.items():
        found = {column: body["description"] for column, body in table["columns"].items()}
        assert found == expected[name]
    loaded = load_fields(contracts)
    for name, table in tables.items():
        assert {f.name: f.description for f in loaded[name]} == {
            column: body["description"] for column, body in table["columns"].items()
        }


def test_required_envelope_fields_have_not_null_and_nothing_has_unique(contracts: Path) -> None:
    text = generate(contracts)
    tables = parsed(text)

    for table in tables.values():
        with_not_null = {
            column
            for column, body in table["columns"].items()
            if body.get("data_tests") == ["not_null"]
        }
        assert with_not_null == {"park_id", "seq"}
    assert "unique" not in text


def test_a_field_without_a_description_stops_the_generator(
    contracts: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    path = contracts / "beta.odcs.yaml"
    path.write_text(path.read_text().replace("        description: Park rating, 0 to 1000.\n", ""))

    code = main(["--contracts-dir", str(contracts), "--output", str(tmp_path / "x.yml")])

    assert code == 1
    assert "beta.rating: the contract gives the field no description" in capsys.readouterr().err
    assert not (tmp_path / "x.yml").exists()


def test_the_repo_contracts_generate_one_table_per_event_type() -> None:
    event_types = {
        path.name.removesuffix(".odcs.yaml")
        for path in (REPO / "contracts").glob("*.odcs.yaml")
        if path.name != "envelope.odcs.yaml"
    }

    tables = parsed(generate(CONTRACTS_DIR))

    assert set(tables) == event_types
    assert "plugin_stats" in tables


